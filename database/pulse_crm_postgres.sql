-- ---------- 2.1 roles ------------------------------------------------
CREATE TABLE roles (
    role_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    role_name   VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    PRIMARY KEY (role_id),
    CONSTRAINT uq_roles_name UNIQUE (role_name)
);
COMMENT ON TABLE roles IS 'Staff roles that control what users do in the CRM';
COMMENT ON COLUMN roles.role_id IS 'Role identifier';
COMMENT ON COLUMN roles.role_name IS 'Job role name';
COMMENT ON COLUMN roles.description IS 'What the role is responsible for';

-- ---------- 2.2 users (CRM staff) ------------------------------------
CREATE TABLE users (
    user_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    full_name  VARCHAR(100) NOT NULL,
    email      VARCHAR(120) NOT NULL,
    phone      VARCHAR(20),
    role_id    INTEGER NOT NULL,
    manager_id INTEGER,
    hire_date  DATE NOT NULL,
    is_active  BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles (role_id),
    CONSTRAINT fk_users_manager FOREIGN KEY (manager_id) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT chk_users_email CHECK (email LIKE '%_@_%._%')
);
COMMENT ON TABLE users IS 'Sales, marketing and support staff who use the CRM';
COMMENT ON COLUMN users.user_id IS 'User identifier';
COMMENT ON COLUMN users.full_name IS 'Staff member full name';
COMMENT ON COLUMN users.email IS 'Login and contact email';
COMMENT ON COLUMN users.phone IS 'Office mobile number';
COMMENT ON COLUMN users.role_id IS 'Role of the user (FK roles)';
COMMENT ON COLUMN users.manager_id IS 'Line manager (FK users, self reference)';
COMMENT ON COLUMN users.hire_date IS 'Date the user joined';
COMMENT ON COLUMN users.is_active IS 'FALSE when the user has left';
COMMENT ON COLUMN users.created_at IS 'Record creation time';

