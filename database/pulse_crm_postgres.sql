-- 7.1 Convert a lead into account + contact + opportunity (one transaction)
--     CALL sp_convert_lead(307, 'Gwadar Port ERP', 2500000, '2027-01-31', NULL);
CREATE OR REPLACE PROCEDURE sp_convert_lead(
    IN  p_lead_id          INTEGER,
    IN  p_opportunity_name VARCHAR(150),
    IN  p_amount           DECIMAL(14,2),
    IN  p_expected_close   DATE,
    OUT p_opportunity_id   INTEGER
)
LANGUAGE plpgsql
SET search_path = pulse_crm
AS $$
DECLARE
    v_status     VARCHAR(20);
    v_company    VARCHAR(150);
    v_city       VARCHAR(60);
    v_owner      INTEGER;
    v_account_id INTEGER;
    v_contact_id INTEGER;
    v_stage_id   INTEGER;
BEGIN
    SELECT status, company_name, city, owner_user_id
      INTO v_status, v_company, v_city, v_owner
    FROM leads
    WHERE lead_id = p_lead_id
    FOR UPDATE;

    IF v_status IS NULL THEN
        RAISE EXCEPTION 'Lead not found' USING ERRCODE = '45000';
    END IF;
    IF v_status = 'Converted' THEN
        RAISE EXCEPTION 'Lead is already converted' USING ERRCODE = '45000';
    END IF;
    IF v_status = 'Unqualified' THEN
        RAISE EXCEPTION 'Unqualified leads cannot be converted' USING ERRCODE = '45000';
    END IF;

    -- reuse the account if the company already exists
    SELECT account_id INTO v_account_id
    FROM accounts
    WHERE account_name = v_company;

    IF v_account_id IS NULL THEN
        INSERT INTO accounts (account_name, account_type, city, owner_user_id)
        VALUES (v_company, 'Prospect', COALESCE(v_city, 'Karachi'), v_owner)
        RETURNING account_id INTO v_account_id;
    END IF;

    INSERT INTO contacts (account_id, first_name, last_name, job_title, email, phone, is_primary)
    SELECT v_account_id, first_name, last_name, job_title, email, phone, TRUE
    FROM leads
    WHERE lead_id = p_lead_id
    RETURNING contact_id INTO v_contact_id;

    SELECT stage_id INTO v_stage_id
    FROM pipeline_stages
    WHERE stage_name = 'Qualification';

    INSERT INTO opportunities (opportunity_name, account_id, primary_contact_id, lead_id,
                               owner_user_id, stage_id, amount, expected_close_date)
    VALUES (p_opportunity_name, v_account_id, v_contact_id, p_lead_id,
            v_owner, v_stage_id, p_amount, p_expected_close)
    RETURNING opportunity_id INTO p_opportunity_id;

    INSERT INTO opportunity_stage_history (opportunity_id, from_stage_id, to_stage_id, changed_by)
    VALUES (p_opportunity_id, NULL, v_stage_id, v_owner);

    UPDATE leads
    SET status = 'Converted',
        converted_account_id = v_account_id,
        converted_at = LOCALTIMESTAMP
    WHERE lead_id = p_lead_id;
END;
$$;

-- 7.2 Move a deal to another stage; a won deal gets its invoice in the same transaction
--     CALL sp_update_opportunity_stage(410, 'Closed Won', 2, NULL);
CREATE OR REPLACE PROCEDURE sp_update_opportunity_stage(
    IN p_opportunity_id INTEGER,
    IN p_stage_name     VARCHAR(50),
    IN p_user_id        INTEGER,
    IN p_loss_reason    VARCHAR(255)
)
LANGUAGE plpgsql
SET search_path = pulse_crm
AS $$
DECLARE
    v_stage_id       INTEGER;
    v_is_closed      BOOLEAN;
    v_is_won         BOOLEAN;
    v_current_stage  INTEGER;
    v_current_closed BOOLEAN;
    v_amount         DECIMAL(14,2);
BEGIN
    SELECT stage_id, is_closed, is_won
      INTO v_stage_id, v_is_closed, v_is_won
    FROM pipeline_stages
    WHERE stage_name = p_stage_name;

    IF v_stage_id IS NULL THEN
        RAISE EXCEPTION 'Unknown pipeline stage' USING ERRCODE = '45000';
    END IF;
    IF v_is_closed = TRUE AND v_is_won = FALSE AND p_loss_reason IS NULL THEN
        RAISE EXCEPTION 'A loss reason is required for Closed Lost' USING ERRCODE = '45000';
    END IF;

    SELECT o.stage_id, s.is_closed, o.amount
      INTO v_current_stage, v_current_closed, v_amount
    FROM opportunities o
    JOIN pipeline_stages s ON o.stage_id = s.stage_id
    WHERE o.opportunity_id = p_opportunity_id
    FOR UPDATE OF o;

    IF v_current_stage IS NULL THEN
        RAISE EXCEPTION 'Opportunity not found' USING ERRCODE = '45000';
    END IF;
    IF v_current_closed = TRUE THEN
        RAISE EXCEPTION 'Opportunity is already closed' USING ERRCODE = '45000';
    END IF;

    -- read by trg_opportunities_stage_history; TRUE = until the end of this transaction
    PERFORM set_config('pulse_crm.user_id', p_user_id::TEXT, TRUE);

    UPDATE opportunities
    SET stage_id          = v_stage_id,
        actual_close_date = CASE WHEN v_is_closed THEN CURRENT_DATE END,
        loss_reason       = CASE WHEN v_is_closed AND NOT v_is_won THEN p_loss_reason END
    WHERE opportunity_id = p_opportunity_id;

    IF v_is_won = TRUE THEN
        INSERT INTO invoices (invoice_number, opportunity_id, invoice_date, due_date, total_amount, status)
        VALUES ('INV-' || EXTRACT(YEAR FROM CURRENT_DATE)::INTEGER || '-' || LPAD(p_opportunity_id::TEXT, 4, '0'),
                p_opportunity_id, CURRENT_DATE, CURRENT_DATE + 30, v_amount, 'Unpaid');
    END IF;

    PERFORM set_config('pulse_crm.user_id', '', TRUE);
END;
$$;

-- 7.3 Record a payment and update the invoice status (one transaction)
--     CALL sp_record_payment(907, 500000, 'Bank Transfer', 'BT-26-0410');
CREATE OR REPLACE PROCEDURE sp_record_payment(
    IN p_invoice_id INTEGER,
    IN p_amount     DECIMAL(14,2),
    IN p_method     VARCHAR(20),
    IN p_reference  VARCHAR(50)
)
LANGUAGE plpgsql
SET search_path = pulse_crm
AS $$
DECLARE
    v_total  DECIMAL(14,2);
    v_status VARCHAR(20);
    v_paid   DECIMAL(14,2);
BEGIN
    SELECT total_amount, status
      INTO v_total, v_status
    FROM invoices
    WHERE invoice_id = p_invoice_id
    FOR UPDATE;

    IF v_total IS NULL THEN
        RAISE EXCEPTION 'Invoice not found' USING ERRCODE = '45000';
    END IF;
    IF v_status IN ('Paid', 'Cancelled') THEN
        RAISE EXCEPTION 'Invoice is already paid or cancelled' USING ERRCODE = '45000';
    END IF;

    SELECT COALESCE(SUM(amount), 0) INTO v_paid
    FROM payments
    WHERE invoice_id = p_invoice_id;

    IF p_amount <= 0 OR v_paid + p_amount > v_total THEN
        RAISE EXCEPTION 'Payment must be positive and cannot exceed the balance due' USING ERRCODE = '45000';
    END IF;

    INSERT INTO payments (invoice_id, payment_date, amount, payment_method, reference_no)
    VALUES (p_invoice_id, CURRENT_DATE, p_amount, p_method, p_reference);

    UPDATE invoices
    SET status = CASE WHEN v_paid + p_amount = v_total THEN 'Paid' ELSE 'Partially Paid' END
    WHERE invoice_id = p_invoice_id;
END;
$$;

-- 7.4 Account 360 summary and its open deals (two result sets)
--     A PostgreSQL procedure returns result sets as cursors:
--       BEGIN;
--       CALL sp_account_summary(101);
--       FETCH ALL FROM account_360;
--       FETCH ALL FROM open_deals;
--       COMMIT;
CREATE OR REPLACE PROCEDURE sp_account_summary(
    IN    p_account_id INTEGER,
    INOUT p_account    REFCURSOR DEFAULT 'account_360',
    INOUT p_open_deals REFCURSOR DEFAULT 'open_deals'
)
LANGUAGE plpgsql
SET search_path = pulse_crm
AS $$
BEGIN
    OPEN p_account FOR
        SELECT *
        FROM vw_account_360
        WHERE account_id = p_account_id;

    OPEN p_open_deals FOR
        SELECT opportunity_id, opportunity_name, stage_name, amount, weighted_amount, expected_close_date
        FROM vw_sales_pipeline
        WHERE account_name = (SELECT account_name FROM accounts WHERE account_id = p_account_id)
          AND is_closed = FALSE
        ORDER BY expected_close_date;
END;
$$;

-- 7.5 Open and weighted pipeline of one sales rep (OUT parameters)
--     CALL sp_sales_rep_pipeline(3, NULL, NULL);
CREATE OR REPLACE PROCEDURE sp_sales_rep_pipeline(
    IN  p_user_id           INTEGER,
    OUT p_open_pipeline     DECIMAL(14,2),
    OUT p_weighted_pipeline DECIMAL(14,2)
)
LANGUAGE plpgsql
SET search_path = pulse_crm
AS $$
BEGIN
    SELECT COALESCE(SUM(amount), 0),
           COALESCE(SUM(weighted_amount), 0)
      INTO p_open_pipeline, p_weighted_pipeline
    FROM vw_sales_pipeline
    WHERE owner_user_id = p_user_id
      AND is_closed = FALSE;
END;
$$;


