-- ---------- 2.4 accounts (companies) ---------------------------------
CREATE TABLE accounts (
    account_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    account_name   VARCHAR(150) NOT NULL,
    industry_id    INTEGER,
    account_type   VARCHAR(20) NOT NULL DEFAULT 'Prospect',
