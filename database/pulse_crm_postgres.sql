--  DBMS: PostgreSQL 15+
--
--  database/pulse_crm.sql (MySQL 8.0) is the original project script.
--  This file is its PostgreSQL translation, used by the live web dashboard.
--  It builds the same 18 tables, constraints, sample data, views, trigger
--  and procedures. The main differences:
--    * MySQL database           -> PostgreSQL schema pulse_crm
--    * AUTO_INCREMENT           -> GENERATED BY DEFAULT AS IDENTITY
--    * TINYINT, DATETIME        -> SMALLINT, TIMESTAMP
--    * inline COMMENT '...'     -> COMMENT ON TABLE / COLUMN
--    * UPDATE ... JOIN          -> UPDATE ... FROM
--    * trigger body             -> PL/pgSQL trigger function
--    * procedures               -> PL/pgSQL; a CALL is atomic, so an error
--                                  rolls back all of its changes
--    * SIGNAL SQLSTATE '45000'  -> RAISE EXCEPTION ... USING ERRCODE '45000'
--    * @crm_user_id             -> transaction setting pulse_crm.user_id
--    * MySQL compares text without regard to case (utf8mb4_0900_ai_ci);
--      PostgreSQL compares it exactly. The sample data is stored the same way.
--    * MySQL's INSERT ... SELECT leaves gaps in AUTO_INCREMENT numbers, so
--      opportunity_stage_history.history_id values differ; the rows match.
--
--  Run it in the Supabase SQL Editor, or:
--    psql "<connection string>" -v ON_ERROR_STOP=1 -f database/pulse_crm_postgres.sql
--  Running it again rebuilds the schema from scratch.
-- =====================================================================

DROP SCHEMA IF EXISTS pulse_crm CASCADE;
CREATE SCHEMA pulse_crm;
