COMMENT ON COLUMN pipeline_stages.stage_id IS 'Stage identifier';
COMMENT ON COLUMN pipeline_stages.stage_name IS 'Stage name';
COMMENT ON COLUMN pipeline_stages.stage_order IS 'Position of the stage in the pipeline';
