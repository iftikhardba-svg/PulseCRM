COMMENT ON COLUMN accounts.account_name IS 'Company name';
COMMENT ON COLUMN accounts.industry_id IS 'Business sector (FK industries)';
COMMENT ON COLUMN accounts.account_type IS 'Prospect, Customer, Partner or Churned';
COMMENT ON COLUMN accounts.website IS 'Company website';
COMMENT ON COLUMN accounts.phone IS 'Main office phone';
COMMENT ON COLUMN accounts.city IS 'Head office city';
COMMENT ON COLUMN accounts.country IS 'Head office country';
COMMENT ON COLUMN accounts.annual_revenue IS 'Company yearly revenue (PKR)';
COMMENT ON COLUMN accounts.employee_count IS 'Number of employees';
COMMENT ON COLUMN accounts.owner_user_id IS 'Account manager (FK users)';
