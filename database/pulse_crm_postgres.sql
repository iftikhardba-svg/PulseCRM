-- ---------- 2.11 opportunity_products (deal line items, M:N) ---------
CREATE TABLE opportunity_products (
    opportunity_id INTEGER NOT NULL,
    product_id     INTEGER NOT NULL,
    quantity       INTEGER NOT NULL DEFAULT 1,
    unit_price     DECIMAL(12,2) NOT NULL,
    discount_pct   DECIMAL(5,2) NOT NULL DEFAULT 0,
    line_total     DECIMAL(14,2) GENERATED ALWAYS AS (ROUND(quantity * unit_price * (1 - discount_pct / 100), 2)) STORED,
    PRIMARY KEY (opportunity_id, product_id),
    CONSTRAINT fk_oppprod_opportunity FOREIGN KEY (opportunity_id) REFERENCES opportunities (opportunity_id) ON DELETE CASCADE,
    CONSTRAINT fk_oppprod_product FOREIGN KEY (product_id) REFERENCES products (product_id),
    CONSTRAINT chk_oppprod_quantity CHECK (quantity > 0),
    CONSTRAINT chk_oppprod_price CHECK (unit_price >= 0),
    CONSTRAINT chk_oppprod_discount CHECK (discount_pct BETWEEN 0 AND 100)
);
COMMENT ON TABLE opportunity_products IS 'Products included in each opportunity (bridge table)';
COMMENT ON COLUMN opportunity_products.opportunity_id IS 'Deal (FK opportunities)';
COMMENT ON COLUMN opportunity_products.product_id IS 'Product on the deal (FK products)';
COMMENT ON COLUMN opportunity_products.quantity IS 'Units or days';
COMMENT ON COLUMN opportunity_products.unit_price IS 'Agreed unit price (PKR)';
COMMENT ON COLUMN opportunity_products.discount_pct IS 'Discount percentage';
COMMENT ON COLUMN opportunity_products.line_total IS 'Calculated line value after discount';

