COMMENT ON TABLE leads IS 'Potential customers captured by marketing and sales';
COMMENT ON COLUMN leads.lead_id IS 'Lead identifier';
COMMENT ON COLUMN leads.first_name IS 'First name';
COMMENT ON COLUMN leads.last_name IS 'Last name';
COMMENT ON COLUMN leads.company_name IS 'Company the lead belongs to';
COMMENT ON COLUMN leads.job_title IS 'Job title';
COMMENT ON COLUMN leads.email IS 'Email address';
COMMENT ON COLUMN leads.phone IS 'Phone number';
COMMENT ON COLUMN leads.city IS 'City';
COMMENT ON COLUMN leads.source_id IS 'Lead channel (FK lead_sources)';
COMMENT ON COLUMN leads.status IS 'New, Contacted, Qualified, Unqualified or Converted';
COMMENT ON COLUMN leads.lead_score IS 'Sales readiness score 0-100';
COMMENT ON COLUMN leads.owner_user_id IS 'Sales owner (FK users)';
COMMENT ON COLUMN leads.converted_account_id IS 'Account created on conversion (FK accounts)';
COMMENT ON COLUMN leads.converted_at IS 'When the lead was converted';
COMMENT ON COLUMN leads.created_at IS 'Record creation time';

-- ---------- 2.8 pipeline_stages --------------------------------------
CREATE TABLE pipeline_stages (
    stage_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    stage_name      VARCHAR(50) NOT NULL,
    stage_order     SMALLINT NOT NULL,
